// GenerateCollectorConfig builds a full OTel Collector YAML pipeline config
// from a Project definition.
func GenerateCollectorConfig(proj Project) (string, error) {
	var sb strings.Builder

	sb.WriteString(collectorHeader(proj.Name))
	sb.WriteString(receiversBlock())
	sb.WriteString(processorBlock(proj))
	sb.WriteString(exportersBlock(proj))
	sb.WriteString(serviceBlock(proj))

	return sb.String(), nil
}

func collectorHeader(name string) string {
	return fmt.Sprintf(`# =============================================================
# ObserveAll — OTel Collector Pipeline Config
# Project: %s
# Generated by: observeall CLI
# =============================================================

`, name)
}

func receiversBlock() string {
	return `receivers:
  # OTLP receiver — accepts traces, metrics, logs via gRPC and HTTP
  otlp:
    protocols:
      grpc:
        endpoint: 0.0.0.0:4317
      http:
        endpoint: 0.0.0.0:4318

  # Prometheus scrape receiver (for infrastructure metrics)
  prometheus:
    config:
      scrape_configs:
        - job_name: 'otel-collector'
          scrape_interval: 10s
          static_configs:
            - targets: ['0.0.0.0:8888']

`
}

func processorBlock(proj Project) string {
	var sb strings.Builder

	sb.WriteString(`processors:
  # Limit memory usage of the collector
  memory_limiter:
    check_interval: 1s
    limit_mib: 512
    spike_limit_mib: 128

  # Batch signals before exporting (improves throughput)
  batch:
    timeout: 5s
    send_batch_size: 1024

  # Enrich all signals with deployment metadata
  resource:
    attributes:
      - key: deployment.environment
        value: production
        action: upsert
      - key: observeall.version
        value: "1.0"
        action: upsert

`)

	if proj.Sampling == "tail" {
		sb.WriteString(`  # Tail-based sampling — makes smart decisions after seeing full traces
  tail_sampling:
    decision_wait: 10s
    num_traces: 100000
    expected_new_traces_per_sec: 1000
    policies:
      # Always sample traces with errors
      - name: errors-policy
        type: status_code
        status_code:
          status_codes: [ERROR]
      # Always sample slow traces (> 500ms)
      - name: slow-traces-policy
        type: latency
        latency:
          threshold_ms: 500
      # Probabilistic 10% fallback for normal traces
      - name: probabilistic-policy
        type: probabilistic
        probabilistic:
          sampling_percentage: 10

`)
	} else if proj.Sampling == "head" {
		sb.WriteString(`  # Head-based probabilistic sampling (1% of all traces)
  probabilistic_sampler:
    sampling_percentage: 1

`)
	}

	if proj.PIIScrubbing {
		piiCfg := pii.PIIConfig{
			Enabled:     true,
			Replacement: proj.PIIReplacement,
		}
		sb.WriteString(pii.GeneratePIIScrubberYAML(piiCfg))
	}

	return sb.String()
}

func exportersBlock(proj Project) string {
	var sb strings.Builder
	sb.WriteString("exporters:\n")

	for _, backend := range proj.Backends {
		cfg := BackendConfig{}
		if proj.BackendConfigs != nil {
			if bc, ok := proj.BackendConfigs[backend]; ok {
				cfg = bc
			}
		}
		sb.WriteString(exporterForBackend(backend, cfg))
	}

	// Always include a debug exporter for development
	sb.WriteString(`  # Debug exporter — prints signals to stdout (useful for development)
  debug:
    verbosity: basic

`)
	return sb.String()
}

func exporterForBackend(backend string, cfg BackendConfig) string {
	switch backend {
	case "prometheus", "prometheus+grafana":
		endpoint := cfg.Endpoint
		if endpoint == "" {
			endpoint = "http://prometheus:9090/api/v1/write"
		}
		return fmt.Sprintf(`  # Prometheus Remote Write exporter
  prometheusremotewrite:
    endpoint: %s
    tls:
      insecure: true

`, endpoint)

	case "grafana":
		endpoint := cfg.Endpoint
		if endpoint == "" {
			endpoint = "https://otlp-gateway-prod-us-central-0.grafana.net/otlp"
		}
		apiKey := cfg.APIKey
		if apiKey == "" {
			apiKey = "${env:GRAFANA_TOKEN}"
		}
		return fmt.Sprintf(`  # Grafana Cloud OTLP exporter
  otlp/grafana:
    endpoint: %s
    headers:
      Authorization: Basic %s

`, endpoint, apiKey)

	case "datadog":
		apiKey := cfg.APIKey
		if apiKey == "" {
			apiKey = "${env:DD_API_KEY}"
		}
		site := cfg.Site
		if site == "" {
			site = "datadoghq.com"
		}
		return fmt.Sprintf(`  # Datadog exporter
  datadog:
    api:
      key: %s
      site: %s

`, apiKey, site)

	case "dynatrace":
		endpoint := cfg.Endpoint
		if endpoint == "" {
			endpoint = "${env:DT_ENDPOINT}/api/v2/otlp"
		}
		apiKey := cfg.APIKey
		if apiKey == "" {
			apiKey = "${env:DT_API_TOKEN}"
		}
		return fmt.Sprintf(`  # Dynatrace OTLP exporter
  otlp/dynatrace:
    endpoint: %s
    headers:
      Authorization: Api-Token %s
    tls:
      insecure: false

`, endpoint, apiKey)

	case "newrelic":
		apiKey := cfg.APIKey
		if apiKey == "" {
			apiKey = "${env:NR_LICENSE_KEY}"
		}
		return fmt.Sprintf(`  # New Relic OTLP exporter
  otlp/newrelic:
    endpoint: https://otlp.nr-data.net
    headers:
      api-key: %s

`, apiKey)

	case "jaeger":
		endpoint := cfg.Endpoint
		if endpoint == "" {
			endpoint = "http://jaeger:4317"
		}
		return fmt.Sprintf(`  # Jaeger OTLP exporter
  otlp/jaeger:
    endpoint: %s
    tls:
      insecure: true

`, endpoint)

	case "custom-otlp":
		endpoint := cfg.Endpoint
		if endpoint == "" {
			endpoint = "${env:CUSTOM_OTLP_ENDPOINT}"
		}
		return fmt.Sprintf(`  # Custom OTLP exporter
  otlp/custom:
    endpoint: %s
    tls:
      insecure: true

`, endpoint)

	default:
		return fmt.Sprintf("  # Unknown backend: %s\n\n", backend)
	}
}

func serviceBlock(proj Project) string {
	var sb strings.Builder
	sb.WriteString("service:\n  pipelines:\n")

	hasTraces := containsSignal(proj.Signals, "traces")
	hasMetrics := containsSignal(proj.Signals, "metrics")
	hasLogs := containsSignal(proj.Signals, "logs")

	traceExporters := buildExporterList(proj.Backends, "traces")
	metricExporters := buildExporterList(proj.Backends, "metrics")
	logExporters := buildExporterList(proj.Backends, "logs")

	samplerProcessor := ""
	if proj.Sampling == "tail" {
		samplerProcessor = "tail_sampling, "
	} else if proj.Sampling == "head" {
		samplerProcessor = "probabilistic_sampler, "
	}

	piiProcessor := ""
	if proj.PIIScrubbing {
		piiProcessor = ", transform/pii_scrubber"
	}

	formatExporters := func(list []string) string {
		all := append(list, "debug")
		return strings.Join(all, ", ")
	}

	if hasTraces {
		sb.WriteString(fmt.Sprintf(`    traces:
      receivers: [otlp]
      processors: [memory_limiter, %sbatch, resource%s]
      exporters: [%s]
`, samplerProcessor, piiProcessor, formatExporters(traceExporters)))
	}

	if hasMetrics {
		sb.WriteString(fmt.Sprintf(`    metrics:
      receivers: [otlp, prometheus]
      processors: [memory_limiter, batch, resource%s]
      exporters: [%s]
`, piiProcessor, formatExporters(metricExporters)))
	}

	if hasLogs {
		sb.WriteString(fmt.Sprintf(`    logs:
      receivers: [otlp]
      processors: [memory_limiter, batch, resource%s]
      exporters: [%s]
`, piiProcessor, formatExporters(logExporters)))
	}

	sb.WriteString(`
  telemetry:
    logs:
      level: info
    metrics:
      address: 0.0.0.0:8888
`)
	return sb.String()
}

func buildExporterList(backends []string, signal string) []string {
	var exporters []string
	for _, b := range backends {
		switch b {
		case "prometheus", "prometheus+grafana":
			if signal == "metrics" {
				exporters = append(exporters, "prometheusremotewrite")
			}
		case "jaeger":
			if signal == "traces" {
				exporters = append(exporters, "otlp/jaeger")
			}
		case "grafana":
			exporters = append(exporters, "otlp/grafana")
		case "datadog":
			exporters = append(exporters, "datadog")
		case "dynatrace":
			exporters = append(exporters, "otlp/dynatrace")
		case "newrelic":
			exporters = append(exporters, "otlp/newrelic")
		case "custom-otlp":
			exporters = append(exporters, "otlp/custom")
		}
	}
	return exporters
}

func containsSignal(signals []string, signal string) bool {
	for _, s := range signals {
		if s == signal {
			return true
		}
	}
	return false
}

// GenerateDockerCompose builds a docker-compose.yaml for local dev.
func GenerateDockerCompose(proj Project) (string, error) {
	tmpl := template.Must(template.New("dc").Parse(dockerComposeTmpl))
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, proj); err != nil {
		return "", err
	}
	return buf.String(), nil
}

